// Generates lib/geo/country-ids.ts: ISO alpha-2 code -> id of its polygon in world-atlas countries-110m
// (the atlas uses numeric ids). Each country is matched by name, then by which polygon contains its
// point in lib/geo/countries.ts. Countries too small for the 110m atlas (Singapore, Malta...) have no
// polygon and are left out; they still get a marker. Run with: npm run build:country-ids
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import { COUNTRIES } from "../lib/geo/countries";

type Props = { name: string };
const topology = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/countries-110m.json", import.meta.url), "utf8"),
) as Topology<{ countries: GeometryCollection<Props> }>;
const features = feature(topology, topology.objects.countries).features;

const norm = (s: string) => s.toLowerCase().normalize("NFKD").replace(/[^a-z]/g, "");
// Where Natural Earth spells a country differently from lib/geo/countries.ts.
const ALIAS: Record<string, string> = {
  US: "United States of America",
  CD: "Dem. Rep. Congo",
  CG: "Congo",
  BA: "Bosnia and Herz.",
  DO: "Dominican Rep.",
  CF: "Central African Rep.",
  GQ: "Eq. Guinea",
  SZ: "eSwatini",
  SB: "Solomon Is.",
  SS: "S. Sudan",
  CI: "Côte d'Ivoire",
  TR: "Turkey",
};

const ids: Record<string, string> = {};
const byCentroid: string[] = [];
const claimed = new Set<string>();

// Pass 1: by name. Pass 2: by containing polygon, but only a polygon no other country has claimed,
// so a microstate (Andorra, Singapore) is never drawn as its big neighbour.
for (const [code, c] of Object.entries(COUNTRIES)) {
  const f = features.find((x) => norm(x.properties.name) === norm(ALIAS[code] ?? c.name));
  if (f && f.id !== undefined) {
    ids[code] = String(f.id);
    claimed.add(String(f.id));
  }
}
for (const [code, c] of Object.entries(COUNTRIES)) {
  if (ids[code]) continue;
  const f = features.find((x) => x.id !== undefined && !claimed.has(String(x.id)) && geoContains(x, [c.lon, c.lat]));
  if (f && f.id !== undefined) {
    ids[code] = String(f.id);
    claimed.add(String(f.id));
    byCentroid.push(`${code} ${c.name} -> ${f.properties.name}`);
  }
}
const unmatched = Object.entries(COUNTRIES)
  .filter(([code]) => !ids[code])
  .map(([code, c]) => `${code} ${c.name}`);
const body = Object.entries(ids)
  .map(([code, id]) => `  ${code}: "${id}",`)
  .join("\n");
writeFileSync(
  new URL("../lib/geo/country-ids.ts", import.meta.url),
  `// Generated by scripts/build-country-ids.ts. Do not edit by hand.\n// ISO alpha-2 -> id of the country's polygon in world-atlas countries-110m.\nexport const COUNTRY_POLYGON_IDS: Readonly<Record<string, string>> = {\n${body}\n};\n`,
);
console.log(`Matched ${Object.keys(ids).length} of ${Object.keys(COUNTRIES).length} countries.`);
console.log(`Matched by position (check these): ${byCentroid.join("; ") || "none"}`);
console.log(`No polygon in the 110m atlas (marker only): ${unmatched.join(", ")}`);
